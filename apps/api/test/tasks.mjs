import { performance } from "node:perf_hooks";
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { withApp } from './harness.mjs';
await withApp(async ({ call, db }) => {
  assert.equal((await call('/tasks', { anonymous: true })).status, 401);
  assert.equal((await call('/tasks/' + randomUUID())).status, 404);
  const setupKey = randomUUID();
  const setup = { timezone: 'Asia/Tehran', workEffectiveFrom: '2026-11-07' };
  const firstSetup = await call('/settings/onboarding', { method: 'POST', key: setupKey, body: setup });
  assert.equal(firstSetup.status, 200); assert.equal(firstSetup.data.onboardingComplete, true);
  assert.deepEqual((await call('/settings/onboarding', { method: 'POST', key: setupKey, body: setup })).data, firstSetup.data);
  assert.equal((await db.query('SELECT count(*)::int AS n FROM "FixedSeries"')).rows[0].n, 1);
  const query = '/schedule?from=2026-11-06T20:30:00Z&to=2026-11-13T20:30:00Z';
  const started = performance.now();
  const schedule = (await call(query)).data;
  console.log(`Week response: ${Math.round(performance.now() - started)} ms, ${Buffer.byteLength(JSON.stringify(schedule))} bytes, ${schedule.events.length} fixed events.`);
  assert.equal(schedule.events.length, 5); assert.equal(schedule.days.length, 7);
  assert.equal(schedule.events[0].startAt, '2026-11-07T04:30:00.000Z');
  assert.equal(schedule.events[0].endAt, '2026-11-07T09:30:00.000Z');
  assert.equal(schedule.events[0].editable, false); assert.equal(schedule.days[0].occupiedMinutes, 300); assert.equal(schedule.days[0].plannedTaskCount, 0);
  assert.equal((await call('/task-occurrences/' + schedule.events[0].id, { method: 'PATCH', version: 1, body: { status: 'completed' } })).status, 400);
  const key = randomUUID(), create = { title: 'Fixture reading', category: 'reading' };
  const created = await call('/tasks', { method: 'POST', key, body: create }); assert.equal(created.status, 201);
  const task = created.data; assert.equal(task.status, 'incomplete'); assert.ok(task.oneOffOccurrenceId);
  assert.deepEqual((await call('/tasks', { method: 'POST', key, body: create })).data, task);
  assert.equal((await call('/tasks', { method: 'POST', key, body: { title: 'different' } })).status, 409);
  const path = '/task-occurrences/' + task.oneOffOccurrenceId;
  const proposal = { scheduledStartAt: '2026-11-07T09:00:00Z', scheduledEndAt: '2026-11-07T10:00:00Z' };
  assert.equal((await call(path, { method: 'PATCH', body: proposal })).status, 428);
  const conflict = await call(path, { method: 'PATCH', version: 1, body: proposal }); assert.equal(conflict.status, 409); assert.equal(conflict.data.code, 'SCHEDULE_CONFLICT');
  assert.equal(conflict.data.details.conflicts[0].title, 'کار');
  assert.equal((await call(path)).data.scheduledStartAt, null);
  const confirmedBody = { ...proposal, conflictSnapshot: conflict.data.details.conflictSnapshot };
  const writeKey = randomUUID();
  const confirmed = await call(path, { method: 'PATCH', version: 1, key: writeKey, body: confirmedBody }); assert.equal(confirmed.status, 200); assert.equal(confirmed.data.version, 2);
  assert.deepEqual((await call(path, { method: 'PATCH', version: 1, key: writeKey, body: confirmedBody })).data, confirmed.data);
  assert.equal((await call(path, { method: 'PATCH', version: 1, body: { status: 'completed' } })).data.code, 'STALE_VERSION');
  const complete = await call(path, { method: 'PATCH', version: 2, body: { status: 'completed' } }); assert.equal(complete.status, 200); assert.ok(complete.data.completedAt);
  const repeat = await call(path, { method: 'PATCH', version: 3, body: { status: 'completed' } }); assert.equal(repeat.data.completedAt, complete.data.completedAt); assert.equal(repeat.data.version, 3);
  assert.equal((await call('/tasks/' + task.id)).data.status, 'completed');
  const reopened = await call(path, { method: 'PATCH', version: 3, body: { status: 'incomplete' } }); assert.equal(reopened.data.completedAt, null);
  const adjacent = await call(path, { method: 'PATCH', version: 4, body: { scheduledStartAt: '2026-11-07T09:30:00Z', scheduledEndAt: '2026-11-07T10:30:00Z' } }); assert.equal(adjacent.status, 200);
  const priorities = (await call('/daily-priorities/2026-11-07')).data;
  assert.equal((await call('/daily-priorities/2026-11-07', { method: 'PUT', version: priorities.version, body: { occurrenceIds: [task.oneOffOccurrenceId] } })).status, 200);
  assert.equal((await call(query)).data.days[0].plannedTaskCount, 1);
  const unscheduled = await call(path, { method: 'PATCH', version: 5, body: { scheduledStartAt: null, scheduledEndAt: null } }); assert.equal(unscheduled.status, 200);
  assert.equal((await call(query)).data.events.length, 5);
  assert.equal((await call('/tasks?view=unscheduled')).data.items.length, 1);
  assert.equal((await call(path)).data.scheduledStartAt, null);
  assert.equal((await call('/tasks/' + task.id, { method: 'PATCH', version: 1, body: { title: 'Revised fixture' } })).status, 200);
  assert.equal((await call(path)).data.snapshot.title, 'Revised fixture');
  assert.equal((await call('/tasks/' + task.id, { method: 'DELETE', version: 2 })).status, 200);
  assert.equal((await call('/tasks')).data.items.length, 0);
  assert.equal((await call(path)).status, 404);
  assert.equal((await call('/schedule?from=2026-01-01T00:00:00Z&to=2027-01-01T00:00:00Z')).status, 400);
  console.log('PASS: onboarding, five work days, task CRUD, inbox, conflicts, confirmation, versions, replay, complete/reopen, unschedule, priorities, and ownership/anonymous denial.');
});
